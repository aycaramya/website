/* builds track-history.js: every committed version of each track's note
   in sisyphus.html, oldest first, so the tracklist can scrub back through
   them. runs in the deploy workflow; run it locally to preview:

     node scripts/build-track-history.mjs

   songs are matched across commits by title, not by li id, since the ids
   shift whenever a track is inserted or reordered. if you ever rename a
   song, give its <li> a data-song="old title" so its history follows it. */

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const FILE = 'sisyphus.html';
const OUT  = 'track-history.js';

const git = (...args) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 << 20 });

const decode = (s) => s
  .replace(/&nbsp;/g, ' ').replace(/&#39;|&rsquo;|&apos;/g, "'")
  .replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const stripTags = (s) => s.replace(/<[^>]*>/g, '');
const squash = (s) => s.replace(/\s+/g, ' ').trim();

/* must match songKey() in js/sisyphus.js */
const songKey = (s) => squash(decode(stripTags(s))).toLowerCase();

/* the first commits had stand-in notes ("updated —— / notes.") — skip those */
function isTemplate(note) {
  const body = squash(decode(stripTags(note.replace(/<p class="meta">[\s\S]*?<\/p>/, ''))));
  return /——/.test(note) || /^(notes\.|why it went\.)?$/i.test(body);
}

function tracksIn(html) {
  const out = [];
  for (const [, attrs, inner] of html.matchAll(/<li id="t\d+"([^>]*)>([\s\S]*?)<\/li>/g)) {
    const summary = inner.match(/<summary>([\s\S]*?)<\/summary>/);
    const note    = inner.match(/<div class="note">([\s\S]*?)<\/details>/);
    if (!summary || !note) continue;
    const alias = attrs.match(/data-song="([^"]*)"/);
    const title = summary[1].replace(/<span class="moved">[\s\S]*?<\/span>/g, '');
    out.push({
      key:  songKey(alias ? alias[1] : title),
      html: note[1].replace(/<\/div>\s*$/, '').trim(),
    });
  }
  return out;
}

const commits = git('log', '--reverse', '--format=%H %as', '--', FILE)
  .trim().split('\n').filter(Boolean)
  .map((line) => { const [hash, date] = line.split(' '); return { hash, date }; });

const history = {};
for (const { hash, date } of commits) {
  for (const { key, html } of tracksIn(git('show', `${hash}:${FILE}`))) {
    if (!key || isTemplate(html)) continue;
    const versions = history[key] || (history[key] = []);
    const last = versions[versions.length - 1];
    if (last && squash(last.html) === squash(html)) continue;   // whitespace-only edit
    versions.push({ date, html });
  }
}

writeFileSync(OUT,
  '/* generated by scripts/build-track-history.mjs — do not edit */\n' +
  'window.TRACK_HISTORY = ' + JSON.stringify(history) + ';\n');

const counts = Object.entries(history).map(([k, v]) => `  ${v.length}  ${k}`).join('\n');
console.log(`${OUT}: ${commits.length} commits scanned\n${counts}`);
